def gen_fold():
    emit('''
# ==== U32 tree reductions (D4): per-leaf Kernel.fold from z, combined at the nodes; the tree comes back ====

def CK.fold.w.l(+n: U32, +d: Nat, r: Array<U32> & U32) -> CH.CW & U32:
  (a, x) = r
  (CH.WL{n, d, a}, x)

def CK.fold.w.j(~c: U32 -> U32 -> U32, +rows: U32, +lrows: U32, x: CH.CW & U32, y: CH.CW & U32) -> CH.CW & U32:
  (l, +a) = x
  (r, +b) = y
  (CH.WN{rows, lrows, l, r}, c(a, b))

# f folded over each leaf's rows from z (Kernel.fold), the leaves' results combined by c at the nodes (one
# fork per node). With c = f associative and z its identity this is the row-order fold (LAWS section 22:
# ck_sum for U32.add, ck_min / ck_max for U32.min / U32.max); the tree is BORROWED
def CK.fold.w(~f: U32 -> U32 -> U32, ~c: U32 -> U32 -> U32, t: CH.CW, +z: U32) -> CH.CW & U32:
  match t:
    case CH.WL{+n, +d, a}:
      CK.fold.w.l(n, d, K.Kernel.fold(~U32, ~U32, ~f, n, a, z))
    case CH.WN{+rows, +lrows, l, r}:
      x y = CK.fold.w(~f, ~c, l, z) CK.fold.w(~f, ~c, r, z)
      CK.fold.w.j(~c, rows, lrows, x, y)

# the modulo-2^32 sum of the rows (U32 sum; I32 sum as words, two's complement); the tree comes back
def CK.sum.w(t: CH.CW) -> CH.CW & U32:
  CK.fold.w(~(acc => x => U32.add(acc, x)), ~(a => b => U32.add(a, b)), t, 0)

# the number of set words of a 0/1 mask tree (the kept count of a filter, the valid count of a column):
# the sum (LAWS section 22 ck_sum covers both)
def CK.popcount.w(t: CH.CW) -> CH.CW & U32:
  CK.sum.w(t)

# U32 min / max of the rows (identity 2^32 - 1 / 0: an empty tree answers it, the caller's null rule
# applies first, as Eval.nz does for the flat fold1); the tree comes back
def CK.min.w(t: CH.CW) -> CH.CW & U32:
  CK.fold.w(~(acc => x => U32.min(acc, x)), ~(a => b => U32.min(a, b)), t, 4294967295)

def CK.max.w(t: CH.CW) -> CH.CW & U32:
  CK.fold.w(~(acc => x => U32.max(acc, x)), ~(a => b => U32.max(a, b)), t, 0)
''')

